#!/usr/bin/env node
// Rewrites the DATA BLOCK in dashboards/yoni-command-center.html from
// dashboards/pull/out/data-constants.json. Nothing outside the block is touched.
// Then checks the page script still parses.
//
// Usage: node dashboards/pull/apply-constants.mjs [--html=path] [--constants=path]

import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const arg = (name) => { const a = process.argv.find((x) => x.startsWith("--" + name + "=")); return a ? a.split("=").slice(1).join("=") : null; };
const htmlPath = arg("html") || path.join(here, "..", "yoni-command-center.html");
const constPath = arg("constants") || path.join(here, "out", "data-constants.json");
const D = JSON.parse(fs.readFileSync(constPath, "utf8"));

const START = "/* ===== DATA BLOCK";
const END = "END DATA BLOCK ===== */";
const html = fs.readFileSync(htmlPath, "utf8");
const i = html.indexOf(START), j = html.indexOf(END);
if (i === -1 || j === -1 || j < i) { console.error("DATA BLOCK markers not found in " + htmlPath); process.exit(2); }

const rows = (name, arr) => "const " + name + " = [\n" + arr.map((r) => "  " + JSON.stringify(r) + ",\n").join("") + "];\n";
let block = START + " (generated by dashboards/pull/apply-constants.mjs, pulled " + (D.pulledAt || "") + ") ===== */\n";
block += 'const DATA_DATE = ' + JSON.stringify(D.DATA_DATE) + ';\nconst TODAY = ' + JSON.stringify(D.TODAY) + ';\n';
block += rows("OVERDUE", D.OVERDUE) + rows("DUE_TODAY", D.DUE_TODAY) + rows("UPCOMING", D.UPCOMING) + rows("CAMPAIGNS", D.CAMPAIGNS) + rows("DEALS", D.DEALS);
block += "\n/* Master Inbox replies, trailing 7 days. `pd` is the Pipedrive person id whose email matches the lead (null = no record).\n";
block += "   status: synced = qualifying category and a Pipedrive record exists; gap = qualifying category but NO record;\n";
block += "   uncategorized = no category yet; none = a category the automation does not sync. `day` is the reply date in Eastern time. */\n";
block += rows("INBOX_LOG", D.INBOX_LOG);
block += "\nconst YESTERDAY = " + JSON.stringify(D.YESTERDAY) + ";\n";
block += "const LINKEDIN = " + JSON.stringify(D.LINKEDIN) + ";\n";
block += "const PD_META = " + JSON.stringify(D.PD_META) + ";\n";
block += "const INBOXES = " + JSON.stringify(D.INBOXES) + ";\n";
block += "/* Categories the Smartlead-to-Pipedrive automation syncs (Interested, Meeting Request, Follow Up). */\n";
block += 'const SYNC_CATEGORIES = ["Interested", "Meeting Request", "Follow Up"];\n';
block += "/* " + END;

const next = html.slice(0, i) + block + html.slice(j + END.length);
fs.writeFileSync(htmlPath, next);

// parse check on the page script
const scripts = [...next.matchAll(/<script>([\s\S]*?)<\/script>/g)].map((m) => m[1]);
const tmp = path.join(here, "out", "page-script-check.js");
fs.writeFileSync(tmp, scripts[scripts.length - 1]);
execFileSync(process.execPath, ["--check", tmp], { stdio: "inherit" });
console.error("applied constants to " + htmlPath + " and the page script parses");
