#!/usr/bin/env node
/**
 * Regenerates the SEO ISSUES BLOCK in command-center.html from the shared
 * issue-tracker spreadsheet in Google Drive.
 *
 *   GOOGLE_SERVICE_ACCOUNT_JSON=... SEO_TRACKER_FILE_ID=... node pull/pull-seo-tracker.mjs
 *
 * Setup: share the tracker with the service account's client_email, the same way
 * you would share it with a colleague. Viewer access is enough. No domain-wide
 * delegation is needed for this one.
 */
import fs from "node:fs";
import path from "node:path";
import { GoogleAuth } from "../../src/google-auth.js";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const DASH = path.join(ROOT, "command-center.html");
const FILE_ID = process.env.SEO_TRACKER_FILE_ID;
const TAB = process.env.SEO_TRACKER_TAB || "";
const NATIVE_SHEET = "application/vnd.google-apps.spreadsheet";

if (!FILE_ID) throw new Error("SEO_TRACKER_FILE_ID is not set. It is the long id in the spreadsheet URL, between /d/ and /edit.");

const auth = new GoogleAuth([
  "https://www.googleapis.com/auth/drive.readonly",
  "https://www.googleapis.com/auth/spreadsheets.readonly",
]);

/* ---------- locate the file ---------- */
let meta;
try {
  meta = await auth.get(`https://www.googleapis.com/drive/v3/files/${FILE_ID}`, {
    fields: "id,name,mimeType,modifiedTime",
    supportsAllDrives: true,
  });
} catch (err) {
  if (err.status === 404) {
    throw new Error(
      `Drive cannot see file ${FILE_ID} as ${auth.clientEmail}.\n` +
      `Open the spreadsheet, click Share, and give ${auth.clientEmail} Viewer access. ` +
      "A service account is not a member of your Workspace: it only sees files shared with it explicitly."
    );
  }
  throw err;
}

if (meta.mimeType !== NATIVE_SHEET) {
  throw new Error(
    `"${meta.name}" is still an uploaded ${meta.mimeType.includes("spreadsheetml") ? ".xlsx file" : `file (${meta.mimeType})`}, not a Google Sheet.\n` +
    "The Sheets API only reads native Google Sheets, so this needs a one-time conversion:\n" +
    "  open it in Drive > File > Save as Google Sheets, share the new copy with " + auth.clientEmail + ",\n" +
    "  then set SEO_TRACKER_FILE_ID to the new file's id.\n" +
    "Worth doing anyway: the team then edits one live document instead of re-uploading new .xlsx copies."
  );
}

/* ---------- read the rows ---------- */
const range = TAB ? `${TAB}!A1:Z100000` : "A1:Z100000";
const sheet = await auth.get(
  `https://sheets.googleapis.com/v4/spreadsheets/${FILE_ID}/values/${encodeURIComponent(range)}`,
  { majorDimension: "ROWS", valueRenderOption: "UNFORMATTED_VALUE" }
);
const values = sheet.values || [];
if (values.length < 2) throw new Error(`The tracker returned ${values.length} row(s). Expected a header row plus issues.`);

const header = values[0].map((h) => String(h || "").trim());
const col = (name) => {
  const i = header.findIndex((h) => h.toLowerCase() === name.toLowerCase());
  if (i === -1) throw new Error(`The tracker has no "${name}" column. Columns found: ${header.join(", ")}`);
  return i;
};
const IDX = {
  id: col("ID"), cat: col("Category"), page: col("Page"), url: col("URL"),
  issue: col("Issue"), desc: col("Description"), fix: col("Fix"),
  pri: col("Priority"), ref: col("Roadmap ref"), st: col("Status"),
};

const cell = (row, i) => String(row[i] == null ? "" : row[i]).replace(/\s+/g, " ").trim();
const ISSUES = values.slice(1)
  .filter((row) => cell(row, IDX.id))           // trailing blank rows carry a FALSE checkbox and nothing else
  .map((row) => ({
    id: cell(row, IDX.id),
    pri: cell(row, IDX.pri) || "P3",
    ref: cell(row, IDX.ref) || "new",
    cat: cell(row, IDX.cat),
    page: cell(row, IDX.page),
    url: cell(row, IDX.url),
    issue: cell(row, IDX.issue),
    desc: cell(row, IDX.desc),
    fix: cell(row, IDX.fix),
    st: cell(row, IDX.st) || "Open",
  }));

if (!ISSUES.length) throw new Error("Parsed 0 issues. The ID column appears to be empty.");

/* Refuse to publish a suspiciously empty tracker over a populated one: a broken
   export should not silently wipe the page. Override with ALLOW_SHRINK=1. */
const prev = fs.readFileSync(DASH, "utf8");
const prevCount = (prev.match(/"id":"AS-/g) || []).length;
if (prevCount && ISSUES.length < prevCount * 0.5 && process.env.ALLOW_SHRINK !== "1") {
  throw new Error(
    `Refusing to write: the tracker returned ${ISSUES.length} issues but the dashboard currently has ${prevCount}. ` +
    "That looks like a failed read rather than real deletions. Re-run with ALLOW_SHRINK=1 if the drop is genuine."
  );
}

/* ---------- emit ---------- */
const updated = new Date(meta.modifiedTime).toLocaleDateString("en-US", {
  month: "short", day: "numeric", year: "numeric", timeZone: "UTC",
});
const json = JSON.stringify(ISSUES).replace(/<\//g, "<\\/");   // never close the host <script> early

const block =
  `/* ===== SEO ISSUES BLOCK (generated by dashboards/pull/pull-seo-tracker.mjs from the shared\n` +
  `   issue tracker in Google Drive. Hand edits here are overwritten on the next refresh.) ===== */\n` +
  `const SEO_SOURCE_UPDATED = ${JSON.stringify(updated)};\n` +
  `const SEO_ISSUES = ${json};\n` +
  `/* END SEO ISSUES BLOCK ===== */`;

const START = "/* ===== SEO ISSUES BLOCK";
const END = "/* END SEO ISSUES BLOCK ===== */";
const s = prev.indexOf(START);
const e = prev.indexOf(END);
if (s === -1 || e === -1) throw new Error("SEO ISSUES BLOCK markers not found in command-center.html");
fs.writeFileSync(DASH, prev.slice(0, s) + block + prev.slice(e + END.length));

const by = (k) => ISSUES.reduce((o, r) => ((o[r[k]] = (o[r[k]] || 0) + 1), o), {});
console.error([
  "",
  `source           ${meta.name}`,
  `last edited      ${updated}`,
  `issues           ${ISSUES.length}${prevCount ? ` (was ${prevCount})` : ""}`,
  `by status        ${JSON.stringify(by("st"))}`,
  `by priority      ${JSON.stringify(by("pri"))}`,
  `workstreams      ${Object.keys(by("ref")).length}`,
  "",
].join("\n"));
